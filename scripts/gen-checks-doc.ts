// Generates docs/CHECKS.md from the rule definitions so the published check list never drifts from the code.
// Run: `npm run docs:checks`
import "./load-env";
import fs from "node:fs";
import path from "node:path";
import { ALL_RULES, CATEGORY_ORDER } from "../src/lib/dbim/engine";
import { DBIM_VERSION } from "../src/lib/dbim/spec";

const SOURCE = { automated: "Automated", heuristic: "Heuristic", ai: "AI-assessed", manual: "Manual" } as const;
const ORG = { ministry: "Ministry", "org-emblem": "Org with emblem", "org-no-emblem": "Org without emblem" } as const;

const cats = [...CATEGORY_ORDER, ...new Set(ALL_RULES.map((r) => r.category).filter((c) => !CATEGORY_ORDER.includes(c)))];
const bySource = Object.fromEntries(Object.keys(SOURCE).map((s) => [s, ALL_RULES.filter((r) => r.source === s).length]));

const lines = [
  "# DBIM checks",
  "",
  `Every check that dbim-validator runs, generated from the rule definitions in [\`src/lib/dbim/rules\`](../src/lib/dbim/rules). Each check cites the section of the Digital Brand Identity Manual (DBIM) v${DBIM_VERSION} it comes from and, where one exists, the Annexure F checklist item (F.1 applies to all organizations, F.2 to Ministries and Departments).`,
  "",
  `**${ALL_RULES.length} checks:** ${Object.entries(bySource).map(([s, n]) => `${n} ${SOURCE[s as keyof typeof SOURCE].toLowerCase()}`).join(", ")}.`,
  "",
  "- **Automated:** measured directly in the rendered page.",
  "- **Heuristic:** inferred from text and structure; may need confirmation.",
  "- **AI-assessed:** judged by Claude from screenshots and page text (needs `ANTHROPIC_API_KEY`; otherwise shown as \"needs review\").",
  "- **Manual:** cannot be verified from outside the website; listed for the website team to confirm.",
  "",
  "Severity sets the weight in the score: critical 3, major 2, minor 1.",
  "",
  "<!-- Generated by scripts/gen-checks-doc.ts. Do not edit by hand. -->",
];

for (const cat of cats) {
  const rules = ALL_RULES.filter((r) => r.category === cat);
  if (!rules.length) continue;
  lines.push("", `## ${cat}`, "", "| Check | DBIM § | Checklist | Type | Severity | Applies to |", "|---|---|---|---|---|---|");
  for (const r of rules)
    lines.push(
      `| ${r.title.replace(/\|/g, "\\|")} | ${r.section} | ${r.checklist ?? ""} | ${SOURCE[r.source]} | ${r.severity} | ${r.appliesTo ? r.appliesTo.map((o) => ORG[o]).join(", ") : "All"} |`,
    );
}

const out = path.join(process.cwd(), "docs", "CHECKS.md");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${out} (${ALL_RULES.length} checks)`);
